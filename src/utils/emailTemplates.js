const TEMPLATES_KEY = 'recruitment_email_templates_v2';

export const getStoredTemplates = () => {
  const saved = localStorage.getItem(TEMPLATES_KEY);
  if (saved) {
    try {
      return { ...DEFAULT_TEMPLATES, ...JSON.parse(saved) };
    } catch (e) {
      console.error('Error loading stored templates', e);
    }
  }
  return DEFAULT_TEMPLATES;
};

export const saveStoredTemplates = (templates) => {
  localStorage.setItem(TEMPLATES_KEY, JSON.stringify(templates));
};

export const renderTemplate = (templateString, variables = {}) => {
  if (!templateString) return '';
  let rendered = templateString;

  Object.keys(variables).forEach((key) => {
    const val = variables[key] !== undefined && variables[key] !== null ? String(variables[key]) : '';
    const regex = new RegExp(`{{${key}}}`, 'g');
    rendered = rendered.replace(regex, val);
  });

  return rendered;
};
